"""RESPOND: draft reply to the prospect, tailored to the verdict.

Generated by the FAST small model (model-per-step: the planner reasons,
the responder writes). Only runs when a fast model is configured — the
CLI omits the draft reply rather than faking it with a template.

GO → accept + propose a call. PILOT → propose the small first step.
NO-GO → polite decline with the honest reason. ESCALATE → holding reply
asking for the missing information (the call questions), no commitment.
"""
from __future__ import annotations

from .decide import Verdict

_SYSTEM = (
    "You draft a short reply from a freelance services provider to an "
    "inbound prospect. 3 sentences max, plain language, no invented "
    "clients, prices, or guarantees. Match the instructed intent exactly."
)

_INTENT = {
    "GO": "Accept the project warmly and propose a 20-minute discovery call.",
    "PILOT": "Propose a small paid pilot as the first step before a full engagement.",
    "NO-GO": "Decline politely, giving the honest reason in one sentence.",
    "ESCALATE": "Thank them and ask for the missing information before committing.",
}


def draft_reply(llm, brief: str, verdict: Verdict) -> dict | None:
    """Return {"text", "model"} or None when the fast model is unavailable."""
    fast = getattr(llm, "generate_fast", None)
    if fast is None:
        return None
    resp = fast(_SYSTEM,
                f"BRIEF:\n{brief[:600]}\n\nVERDICT: {verdict.verdict}\n"
                f"REASON: {verdict.reason[:200]}\n"
                f"QUESTIONS TO ASK: {'; '.join(verdict.call_questions)}\n\n"
                f"INTENT: {_INTENT.get(verdict.verdict, _INTENT['ESCALATE'])}")
    if resp is None:
        return None
    return {"text": resp.text.strip(), "model": resp.model}
